#!/usr/bin/env python3
"""PreToolUse hook for Edit/Write: protect generated and sensitive files.

- sitemap.xml must never be created or edited (it is generated by sitemap.php;
  add pages to sitemap-static.xml instead): denied.
- admin/config.php and send_mail.php hold credentials and the mail target:
  Claude must ask the owner first.
"""
import json
import os
import sys

try:
    data = json.load(sys.stdin)
except ValueError:
    sys.exit(0)

path = (data.get("tool_input") or {}).get("file_path", "")
root = os.environ.get("CLAUDE_PROJECT_DIR", os.getcwd())
rel = os.path.relpath(path, root).replace(os.sep, "/") if path else ""


def decide(kind, reason):
    print(json.dumps({"hookSpecificOutput": {
        "hookEventName": "PreToolUse",
        "permissionDecision": kind,
        "permissionDecisionReason": reason}}))
    sys.exit(0)


if rel == "sitemap.xml":
    decide("deny", "sitemap.xml is generated by sitemap.php. Add the URL to sitemap-static.xml instead (CLAUDE.md section 9).")
if rel in ("admin/config.php", "send_mail.php"):
    decide("ask", f"{rel} holds credentials or the mail destination. Confirm with the owner before changing it (CLAUDE.md section 10).")
sys.exit(0)
